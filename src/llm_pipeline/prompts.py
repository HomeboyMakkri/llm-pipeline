def build_prompt(text: str) -> str:
    """Сформировать инструкцию для обработки текста моделью."""
    return (
        "Проанализируй текст ниже и представь результат в трёх частях:\n"
        "1. Краткое содержание.\n"
        "2. Три ключевые мысли.\n"
        "3. Короткий полезный ответ по содержанию текста.\n\n"
        f"Текст:\n{text}"
    )
